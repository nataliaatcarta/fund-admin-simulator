// Everyday texture: repeatable inbox items, check-in meetings and desk (mini-game) items.
// All ids are prefixed `f_`. Story events live in events-story.ts (ids `s_`).
import { Category, Choice, Cond, Effects, GameEvent, Line, Mood, NpcId } from "../game/types";

type Opt = [text: string, reply: Line, effects: Effects, mood?: Mood];

const mk = (id: string, o: Opt, i: number): Choice => ({
  id: `${id}_${"abc"[i]}`,
  text: o[0],
  reply: o[1],
  effects: o[2],
  ...(o[3] ? { replyMood: o[3] } : {}),
});

interface QuickSpec {
  id: string;
  cat: Category;
  who: NpcId | "system";
  kind: "email" | "call" | "sticky";
  subj: string;
  setup: Line;
  a: Opt;
  b: Opt;
  w?: number;
  seasons?: (1 | 2 | 3 | 4)[];
  cond?: Cond;
  weeks?: number[];
  ignored?: Effects;
  portrait?: string;
}

const quick = (s: QuickSpec): GameEvent => ({
  id: s.id,
  category: s.cat,
  title: s.subj,
  speaker: s.who,
  kind: s.kind,
  subject: s.subj,
  setup: s.setup,
  ...(s.portrait ? { portrait: s.portrait } : {}),
  mode: "quick",
  choices: [mk(s.id, s.a, 0), mk(s.id, s.b, 1)],
  ...(s.ignored ? { ignored: s.ignored } : {}),
  when: {
    once: false,
    weight: s.w ?? 1,
    ...(s.seasons ? { seasons: s.seasons } : {}),
    ...(s.cond ? { cond: s.cond } : {}),
    ...(s.weeks ? { weeks: s.weeks } : {}),
  },
});

interface MeetSpec {
  id: string;
  cat: Category;
  who: NpcId;
  subj: string;
  setup: Line;
  opts: Opt[];
  cond?: Cond;
  w?: number;
  seasons?: (1 | 2 | 3 | 4)[];
  portrait?: string;
}

const meet = (s: MeetSpec): GameEvent => ({
  id: s.id,
  category: s.cat,
  title: s.subj,
  speaker: s.who,
  kind: "call",
  subject: s.subj,
  setup: s.setup,
  ...(s.portrait ? { portrait: s.portrait } : {}),
  mode: "meeting",
  meetingCost: 1,
  choices: s.opts.map((o, i) => mk(s.id, o, i)),
  when: { once: false, weight: s.w ?? 1, ...(s.cond ? { cond: s.cond } : {}), ...(s.seasons ? { seasons: s.seasons } : {}) },
});

interface WireSpec {
  id: string;
  who: NpcId | "system";
  subj: string;
  setup: Line;
  kind: "founder" | "vendor" | "lp";
  name: string;
  w?: number;
  cond?: Cond;
  seasons?: (1 | 2 | 3 | 4)[];
}

const wire = (s: WireSpec): GameEvent => ({
  id: s.id,
  category: "ops",
  title: s.subj,
  speaker: s.who,
  kind: "email",
  subject: s.subj,
  setup: s.setup,
  mode: "desk",
  desk: { game: "wire-check", context: { kind: s.kind, name: s.name } },
  choices: [],
  ignored: { compliance: 3, wellbeing: -1 },
  when: { once: false, weight: s.w ?? 1, ...(s.cond ? { cond: s.cond } : {}), ...(s.seasons ? { seasons: s.seasons } : {}) },
});

